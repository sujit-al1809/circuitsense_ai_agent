"""Builds a ``CircuitAnalysis`` from uploads or bundled samples and stores the session.

Precedence of evidence:
* components & connectivity: parsed netlist (verified) > vision model (inferred)
* bounding boxes: sample annotations (exact, drawn by the generator) > vision model
"""

from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone

from app.config import Settings
from app.schemas.circuit import (
    BoundingBox,
    CircuitAnalysis,
    Component,
    DiagnosticAction,
    Net,
    PreviewInfo,
    Provenance,
    Uncertainty,
)
from app.services.circuit_graph import CircuitGraph
from app.services.circuit_parser import NetlistParseError, ParsedNetlist, parse_netlist
from app.services.diagnostics import build_insight, find_issues, plan_next_check
from app.services.sample_library import SampleCircuit, SampleLibrary
from app.services.storage import Session, SessionStore, UploadArchive
from app.services.vision_service import (
    PreparedDocument,
    UploadValidationError,
    VisionAnalyzer,
    VisionResult,
    detect_kind,
    prepare_document,
)

logger = logging.getLogger(__name__)

DEMO_NOTICE = (
    "Demo mode: no AI model is called. Answers come from CircuitSense's deterministic, rule-based agent "
    "and its tools (netlist parsing, graph tracing, calculations, local datasheet search)."
)
BEDROCK_NOTICE = "Amazon Bedrock mode: answers are generated by the configured Bedrock model using CircuitSense tools."


@dataclass
class UploadedFile:
    filename: str
    data: bytes
    content_type: str | None = None


def new_circuit_id() -> str:
    return f"cir_{uuid.uuid4().hex[:16]}"


def _decode_netlist(data: bytes) -> ParsedNetlist:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise UploadValidationError("The netlist must be UTF-8 text.") from exc
    try:
        return parse_netlist(text)
    except NetlistParseError as exc:
        raise UploadValidationError(f"Netlist could not be parsed: {exc}", code="invalid_netlist") from exc


class AnalysisService:
    def __init__(
        self,
        settings: Settings,
        store: SessionStore,
        samples: SampleLibrary,
        vision: VisionAnalyzer,
        archive: UploadArchive,
    ):
        self.settings = settings
        self.store = store
        self.samples = samples
        self.vision = vision
        self.archive = archive

    # ------------------------------------------------------------------ entry points
    def load_sample(self, sample_id: str) -> Session:
        sample = self.samples.get(sample_id)
        if sample is None:
            raise KeyError(sample_id)
        parsed = parse_netlist(sample.netlist_path.read_text(encoding="utf-8"))
        doc = prepare_document(sample.schematic_path.read_bytes(), "png", self.settings)
        boxes = self._sample_boxes(sample, "png")
        analysis = self._assemble(
            circuit_id=new_circuit_id(),
            source_kind="sample",
            filename=sample.schematic_path.name,
            parsed=parsed,
            vision=None,
            doc=doc,
            sample=sample,
            sample_boxes=boxes,
            extra_notices=[
                f"Bundled sample '{sample.name}': hand-authored reference netlist (verified connectivity) and "
                "exact component locations from the drawing generator."
            ],
        )
        session = Session(analysis=analysis, preview_png=doc.preview_png)
        self.store.save(session)
        return session

    def analyze_upload(self, upload: UploadedFile, netlist: UploadedFile | None = None, page: int = 1) -> Session:
        self._check_size(upload)
        if netlist is not None:
            self._check_size(netlist)
        kind = detect_kind(upload.data)
        circuit_id = new_circuit_id()
        notices: list[str] = []

        if kind == "netlist":
            if netlist is not None:
                raise UploadValidationError("Upload the netlist either as the main file or as the netlist attachment, not both.")
            parsed = _decode_netlist(upload.data)
            analysis = self._assemble(
                circuit_id=circuit_id,
                source_kind="netlist",
                filename=upload.filename,
                parsed=parsed,
                vision=None,
                doc=None,
                extra_notices=["Netlist-only upload: there is no schematic image to display; use the component list."],
            )
            self.store.save(Session(analysis=analysis))
            self.archive.put(circuit_id, upload.filename, upload.data, "text/plain")
            return self.store.get(circuit_id)  # type: ignore[return-value]

        parsed = None
        if netlist is not None:
            if detect_kind(netlist.data) != "netlist":
                raise UploadValidationError("The netlist attachment is not a KiCad netlist (.net).", code="invalid_netlist")
            parsed = _decode_netlist(netlist.data)

        doc = prepare_document(upload.data, kind, self.settings, page=page)
        notices.extend(doc.notes)
        sample_boxes: dict[str, BoundingBox] | None = None
        sample: SampleCircuit | None = None
        vision: VisionResult | None = None

        match = self.samples.match_upload(upload.data) if self.settings.provider_mode == "demo" else None
        if match is not None:
            sample, variant = match
            sample_boxes = self._sample_boxes(sample, variant)
            if parsed is None:
                parsed = parse_netlist(sample.netlist_path.read_text(encoding="utf-8"))
            notices.append(
                f"Demo mode recognised this file as the bundled sample '{sample.name}' (exact file match) and loaded "
                "its reference netlist and annotations. No image recognition was performed."
            )
        else:
            vision = self.vision.analyze(doc)

        analysis = self._assemble(
            circuit_id=circuit_id,
            source_kind="pdf" if kind == "pdf" else "image",
            filename=upload.filename,
            parsed=parsed,
            vision=vision,
            doc=doc,
            sample=sample,
            sample_boxes=sample_boxes,
            extra_notices=notices,
        )
        self.store.save(Session(analysis=analysis, preview_png=doc.preview_png))
        self.archive.put(circuit_id, upload.filename, upload.data, upload.content_type or "application/octet-stream")
        if netlist is not None:
            self.archive.put(circuit_id, netlist.filename, netlist.data, "text/plain")
        return self.store.get(circuit_id)  # type: ignore[return-value]

    # ------------------------------------------------------------------ helpers
    def _check_size(self, upload: UploadedFile) -> None:
        if not upload.data:
            raise UploadValidationError(f"'{upload.filename}' is empty.", code="empty_file")
        if len(upload.data) > self.settings.max_upload_bytes:
            raise UploadValidationError(
                f"'{upload.filename}' is {len(upload.data) / 1_048_576:.1f} MB; the limit is {self.settings.max_upload_mb:g} MB.",
                code="file_too_large",
            )

    @staticmethod
    def _sample_boxes(sample: SampleCircuit, variant: str) -> dict[str, BoundingBox]:
        ann = sample.annotations
        comps = ann.get("pdf", {}).get("components", {}) if variant == "pdf" else ann.get("components", {})
        return {ref: BoundingBox(source="sample_annotation", page=1, **box) for ref, box in comps.items()}

    def _assemble(
        self,
        *,
        circuit_id: str,
        source_kind: str,
        filename: str | None,
        parsed: ParsedNetlist | None,
        vision: VisionResult | None,
        doc: PreparedDocument | None,
        sample: SampleCircuit | None = None,
        sample_boxes: dict[str, BoundingBox] | None = None,
        extra_notices: list[str] | None = None,
    ) -> CircuitAnalysis:
        mode = self.settings.provider_mode
        provenance: list[Provenance] = []
        uncertainties: list[Uncertainty] = []
        notices = [DEMO_NOTICE if mode == "demo" else BEDROCK_NOTICE] + list(extra_notices or [])

        components: list[Component] = []
        nets: list[Net] = []
        if parsed is not None:
            provenance.append("parsed_netlist")
            components = [c.model_copy(deep=True) for c in parsed.components]
            nets = list(parsed.nets)
            for w in parsed.warnings:
                uncertainties.append(Uncertainty(topic="Netlist warning", detail=w))
        if vision is not None:
            uncertainties.extend(vision.uncertainties)
            if vision.available:
                provenance.append("image_inference")
                if parsed is None:
                    components = vision.components
                    nets = vision.nets
                    if vision.nets:
                        uncertainties.append(
                            Uncertainty(
                                topic="Connectivity is inferred",
                                detail="Connections were read from the image by a vision model and are NOT verified. "
                                "Upload a KiCad netlist (.net) to verify them.",
                            )
                        )
                else:
                    netlist_refs = {c.ref for c in components}
                    vision_refs = {c.ref for c in vision.components}
                    boxes = {c.ref: c.bbox for c in vision.components if c.bbox}
                    for c in components:
                        if c.ref in boxes:
                            c.bbox = boxes[c.ref]
                    missing = sorted(vision_refs - netlist_refs)
                    unseen = sorted(netlist_refs - vision_refs)
                    if missing:
                        uncertainties.append(Uncertainty(topic="Image/netlist mismatch", detail=f"Seen in the image but absent from the netlist: {', '.join(missing)}."))
                    if unseen:
                        uncertainties.append(Uncertainty(topic="Image/netlist mismatch", detail=f"In the netlist but not located in the image: {', '.join(unseen)}."))
        if sample_boxes:
            provenance.append("sample_annotation")
            for c in components:
                if c.ref in sample_boxes:
                    c.bbox = sample_boxes[c.ref]

        verified_nets = [n for n in nets if n.verification == "verified"]
        connectivity = "verified" if verified_nets else ("inferred" if nets else "unavailable")

        title = sample.name if sample else (vision.title if vision and vision.available else (filename or "Circuit"))
        circuit_type = "unknown"
        summary = ""
        expected = sample.expected_behavior if sample else None
        issues = []
        calculations = []
        roles: dict[str, str] = {}
        next_action: DiagnosticAction | None = None

        if verified_nets:
            graph = CircuitGraph(components, verified_nets)
            insight = build_insight(graph)
            circuit_type = insight.circuit_type
            if not sample:
                title = insight.title if insight.circuit_type != "general" else title
            summary = insight.summary
            expected = expected or insight.expected_behavior or None
            uncertainties.extend(insight.uncertainties)
            issues = find_issues(graph, insight)
            calculations = insight.calculations
            roles = dict(insight.roles)
            if calculations:
                provenance.append("calculation")
            next_action = plan_next_check(graph, insight, []).next_action
        elif vision is not None and vision.available:
            circuit_type = vision.circuit_type
            summary = vision.summary
            next_action = DiagnosticAction(
                action="Upload the KiCad netlist (.net) for this schematic, or confirm the connections around the part you are debugging.",
                reason="Connectivity was only inferred from the image. Verified connectivity is needed before tracing nets or trusting calculations.",
            )
        else:
            summary = "No components or connectivity could be determined for this upload."
            next_action = DiagnosticAction(
                action="Upload a KiCad netlist (.net), load a bundled sample, or enable Amazon Bedrock for image interpretation.",
                reason="CircuitSense has no verified or inferred circuit data for this file yet.",
            )
        if connectivity == "unavailable":
            uncertainties.append(
                Uncertainty(topic="Connectivity unavailable", detail="No electrical connections are known for this circuit.")
            )
        if components and not any(c.bbox for c in components) and doc is not None:
            uncertainties.append(
                Uncertainty(topic="Component locations", detail="No component coordinates are available; use the component list instead of the image overlay.")
            )

        preview = None
        if doc is not None:
            preview = PreviewInfo(
                url=f"/api/circuits/{circuit_id}/preview",
                width=doc.width,
                height=doc.height,
                page=doc.page,
                page_count=doc.page_count,
            )
        return CircuitAnalysis(
            circuit_id=circuit_id,
            created_at=datetime.now(timezone.utc),
            mode=mode,
            source_kind=source_kind,  # type: ignore[arg-type]
            source_filename=filename,
            sample_id=sample.id if sample else None,
            title=title,
            circuit_type=circuit_type,
            summary=summary,
            expected_behavior=expected,
            components=components,
            nets=nets,
            connectivity_status=connectivity,  # type: ignore[arg-type]
            provenance=list(dict.fromkeys(provenance)),
            uncertainties=uncertainties,
            issues=issues,
            calculations=calculations,
            component_roles=roles,
            next_action=next_action,
            preview=preview,
            notices=notices,
        )
